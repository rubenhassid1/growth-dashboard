def parse_substack():
    """Parse Substack CSV into {date: count} dict."""
    entries = {}
    for line in SUBSTACK_CSV.strip().split('\n'):
        date_str, count = line.split(',')
        # Convert 2025/05/06 -> 2025-05-06
        date = date_str.replace('/', '-')
        entries[date] = int(count)
    return entries


def parse_x():
    """Parse X CSV into {date: cumulative_count} dict, working back from known total."""
    # Parse rows (newest first)
    rows = []
    for line in X_CSV_ROWS.strip().split('\n'):
        parts = line.split(',')
        # "Fri, Mar 27, 2026" -> need to parse
        date_str = ','.join(parts[:3]).strip()
        new_follows = int(parts[3].strip())
        unfollows = int(parts[4].strip())
        dt = datetime.strptime(date_str, '%a, %b %d, %Y')
        date = dt.strftime('%Y-%m-%d')
        rows.append({'date': date, 'net': new_follows - unfollows})

    # Rows are newest-first. Work backwards from known total.
    rows.sort(key=lambda r: r['date'], reverse=True)
    entries = {}
    running = KNOWN_X_TOTAL
    for r in rows:
        entries[r['date']] = running
        running -= r['net']

    return entries


def fetch_linkedin():
    """Get LinkedIn daily data from the linkedin-fighter Google Sheet."""
    SHEET_ID = '1j_Z8JuukkskQlfgsIzZgiX_XoSGu_rzNuCGLu_asZuo'
    url = f'https://docs.google.com/spreadsheets/d/{SHEET_ID}/export?format=csv'
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(req, timeout=15) as r:
        text = r.read().decode('utf-8')

    entries = {}
    for line in text.strip().split('\n')[1:]:  # skip header
        # Parse CSV with quoted fields
        fields = []
        in_q = False
        field = ''
        for ch in line:
            if ch == '"':
                in_q = not in_q
                continue
            if ch == ',' and not in_q:
                fields.append(field.strip())
                field = ''
                continue
            field += ch
        fields.append(field.strip())

        if len(fields) < 5:
            continue
        # Date is DD/MM/YYYY -> YYYY-MM-DD
        date_parts = fields[0].split('/')
        if len(date_parts) != 3:
            continue
        date = f'{date_parts[2]}-{date_parts[1]}-{date_parts[0]}'
        # Ruben Followers is column 4
        raw = fields[4].replace(',', '')
        if not raw.isdigit():
            continue
        count = int(raw)
        entries[date] = count  # last entry per date wins (most recent hour)

    return entries


